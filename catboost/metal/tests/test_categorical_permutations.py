def test_uniform_uses_upstream_rejection_boundary(monkeypatch):
    # This boundary almost never occurs naturally; modulo-only implementations
    # would accept RandMax and return a different draw for a bound of two.
    random = _CudaMersenne64(0)
    sequence = iter([(1 << 64) - 1, (1 << 64) - 2, 3])
    monkeypatch.setattr(random, "next", lambda: next(sequence))
    assert random.uniform(2) == 1


def _data():
    rng = np.random.default_rng(131)
    rows = 1031
    raw = np.empty((rows, 3), dtype=object)
    raw[:, 0] = [f"category-{index % 43}" for index in range(rows)]
    raw[:, 1] = rng.normal(size=rows)
    raw[:, 2] = np.array(["red", "blue"])[np.arange(rows) % 2]
    targets = rng.integers(0, 2, rows).astype(np.float32)
    return raw, targets


def _prepare(raw, targets, **kwargs):
    return prepare_features(raw, 15, "Forbidden", [0, 2], ["category", "number", "onehot"], 2,
                            targets=targets, objective=kwargs.pop("objective", "Logloss"),
                            permutation_count=kwargs.pop("permutation_count", 4), **kwargs)


def _exclusive_reference(hashes, targets, order):
    history = {}
    values = np.empty(len(hashes), np.float32)
    for row in order:
        key = int(hashes[row])
        total, count = history.get(key, (0, 0))
        values[row] = (total + 0.5) / (count + 1)
        history[key] = total + int(targets[row]), count + 1
    return values


@METAL
def test_four_datasets_share_grid_candidates_and_common_row_order():
    raw, targets = _data()
    layout, bins, features, thresholds, types = _prepare(raw, targets)
    assert layout.permutation_count == 4
    assert layout.estimation_permutation == 3
    assert layout.permutation_bins[0] is bins
    ctr_feature = next(iter(layout.ctrs))
    hashes = cat_feature_hashes(raw[:, 0])
    for permutation, matrix in enumerate(layout.permutation_bins):
        assert matrix.shape == bins.shape and matrix.dtype == np.uint8
        np.testing.assert_array_equal(matrix[:raw.shape[1]], bins[:raw.shape[1]])
        reference = _exclusive_reference(hashes, targets, cuda_history_order(len(raw), permutation))
        np.testing.assert_array_equal(matrix[ctr_feature],
                                      np.searchsorted(layout.borders[ctr_feature], reference, side="left"))
    assert any(not np.array_equal(bins, matrix) for matrix in layout.permutation_bins[1:])
    single, single_bins, *single_candidates = _prepare(raw, targets, permutation_count=1, random_seed=999)
    np.testing.assert_array_equal(bins, single_bins)
    for before, after in zip((features, thresholds, types), single_candidates):
        np.testing.assert_array_equal(before, after)
    for grid, single_grid in zip(layout.borders, single.borders):
        np.testing.assert_array_equal(grid, single_grid)


@METAL
def test_each_history_excludes_its_current_and_future_targets():
    raw, targets = _data()
    layout, *_ = _prepare(raw, targets)
    feature = next(iter(layout.ctrs))
    hashes = cat_feature_hashes(raw[:, 0])
    for permutation in range(4):
        order = cuda_history_order(len(raw), permutation)
        changed = targets.copy()
        changed[order[100:]] = 1 - changed[order[100:]]
        result = compute_ctr(hashes, changed, permutation=order)
        # Keep the original p0 grid fixed. A new global grid may legitimately
        # move borders when future targets change, independently of histories.
        encoded = np.searchsorted(layout.borders[feature], result.values, side="left")
        prefix_including_changed_current_row = order[:101]
        np.testing.assert_array_equal(encoded[prefix_including_changed_current_row],
                                      layout.permutation_bins[permutation][feature, prefix_including_changed_current_row])


@METAL
def test_heldout_uses_full_learn_table_and_shared_grid():
    raw, targets = _data()
    layout, *_ = _prepare(raw, targets)
    feature = next(iter(layout.ctrs))
    heldout = raw[:6].copy()
    heldout[0, 0] = "unseen"
    actual = layout.transform(heldout)
    expected = []
    for category in heldout[:, 0]:
        selected = raw[:, 0] == category
        expected.append((float(targets[selected].sum()) + 0.5) / (int(selected.sum()) + 1))
    np.testing.assert_array_equal(actual[feature],
                                  np.searchsorted(layout.borders[feature], np.array(expected, np.float32), side="left"))
    stats = layout.ctr_gpu_stats
    assert stats["compute_calls"] == 4
    calls = [call for permutation in layout.permutation_stats for call in permutation]
    assert stats["kernel_dispatches"] == sum(call["kernel_dispatches"] for call in calls)
    assert stats["gpu_seconds"] == sum(call["gpu_seconds"] for call in calls)


