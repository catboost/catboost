@METAL
def test_ctr_cardinality_includes_heldout_hashes_by_runtime_column():
    raw, targets = _data()
    layout, *_ = _prepare(raw, targets)
    feature = next(iter(layout.ctrs))
    before = layout.ctr_unique_values()
    np.testing.assert_array_equal(before, [0, 0, 0, 43])
    heldout = raw[:4].copy()
    heldout[:, 0] = ["unseen", "unseen", "other-unseen", "category-0"]
    np.testing.assert_array_equal(layout.ctr_unique_values(heldout), [0, 0, 0, 45])
    np.testing.assert_array_equal(layout.ctr_unique_values(np.empty((0, 3), object)), before)
    np.testing.assert_array_equal(layout.ctr_unique_values(), before)
    # Two prior configurations sharing a source are still distinct runtime
    # columns; later model-size used flags must not collapse these identities.
    first = layout.ctrs[feature]
    layout.borders.append(layout.borders[feature].copy())
    layout.ctrs[len(layout.borders) - 1] = replace(first, result=replace(first.result, prior_numerator=1.0))
    np.testing.assert_array_equal(layout.ctr_unique_values(heldout), [0, 0, 0, 45, 45])
    assert layout.ctr_unique_values(heldout).dtype == np.uint32


@METAL
@pytest.mark.parametrize("objective", ["MultiClass", "MultiClassOneVsAll"])
def test_multiclass_four_permutations_use_one_causal_ctr_grid(objective):
    raw, targets = _data()
    targets = (np.arange(len(targets)) % 3).astype(np.float32)
    layout, bins, candidate_features, _, _ = _prepare(raw, targets, objective=objective)
    assert layout.permutation_count == 4 and layout.estimation_permutation == 3
    # The configured single Borders CTR remains one runtime column. Multiclass
    # must not silently create a separate target-CTR feature for every class.
    assert len(layout.ctrs) == 1
    feature, ctr = next(iter(layout.ctrs.items()))
    assert bins.shape == (raw.shape[1] + 1, len(raw))
    assert set(candidate_features[candidate_features >= raw.shape[1]]) == {feature}
    hashes = cat_feature_hashes(raw[:, 0])
    ctr_targets = (targets > ctr.target_border).astype(np.float32)
    for permutation, matrix in enumerate(layout.permutation_bins):
        np.testing.assert_array_equal(matrix[:raw.shape[1]], bins[:raw.shape[1]])
        order = cuda_history_order(len(raw), permutation)
        expected = _exclusive_reference(hashes, ctr_targets, order)
        np.testing.assert_array_equal(matrix[feature],
                                      np.searchsorted(layout.borders[feature], expected, side="left"))


@METAL
@pytest.mark.parametrize("objective", ["MultiClass", "MultiClassOneVsAll"])
def test_high_cardinality_multiclass_p4_trains_and_exports_on_gpu(tmp_path, objective):
    from catboost import CatBoostClassifier
    from catboost_metal import CatBoostMetalClassifier

    codes = np.tile(np.arange(43), 9)
    rows = np.asarray([[f"category-{code}"] for code in codes], dtype=object)
    targets = np.array(["first", "second", "third"])[codes % 3]
    heldout = [["category-0"], ["category-1"], ["category-2"], ["never-before"]]
    model = CatBoostMetalClassifier(loss_function=objective, iterations=12, depth=2,
                                    learning_rate=.25, leaf_estimation_iterations=2,
                                    cat_features=[0], one_hot_max_size=2, permutation_count=4,
                                    random_seed=7).fit(rows, targets)
    assert model._layout.permutation_count == 4
    assert len(model._layout.ctrs) == 1
    assert model.training_predictions_.shape == (len(rows), 3)
    assert model.training_stats_["permutation_count"] == 4
    assert model.training_stats_["estimation_permutation"] == 3
    assert model.training_stats_["ctr_kernel_dispatches"] == model._layout.ctr_gpu_stats["kernel_dispatches"]
    assert model.loss_history_[-1] < model.loss_history_[0] * .9
    expected = model.predict(heldout, prediction_type="RawFormulaVal")
    actual = model.predict(heldout, prediction_type="RawFormulaVal", task_type="METAL")
    np.testing.assert_allclose(actual, expected, rtol=3e-5, atol=4e-5)
    assert np.isfinite(actual).all()
    for model_format in ("json", "cbm"):
        path = tmp_path / f"multiclass-ctr.{model_format}"
        model.save_model(path, format=model_format)
        restored = CatBoostClassifier().load_model(str(path), format=model_format)
        np.testing.assert_allclose(restored.predict(heldout, prediction_type="RawFormulaVal"), expected,
                                   rtol=1e-6, atol=1e-7)


