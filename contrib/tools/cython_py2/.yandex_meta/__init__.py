import os
import re
import shutil

from devtools.yamaker.fileutil import re_sub_file
from devtools.yamaker.project import NixProject
from devtools.yamaker.modules import Linkable, Words
from devtools.yamaker import python

from pathlib import Path


def runtime_files(root):
    root = Path(root)
    sources = ["cython.py"]
    data = []
    for path in sorted((root / "Cython").rglob("*")):
        if not path.is_file() or "__pycache__" in path.parts:
            continue
        relative = path.relative_to(root).as_posix()
        if path.suffix == ".py" and "Tests" not in path.parts:
            sources.append(relative)
        if Path(relative).parts[:2] in (("Cython", "Includes"), ("Cython", "Utility")):
            if path.name != "ya.make":
                data.append(relative)
    return sorted(sources), sorted(data)


def write_dependencies(root, arcdir):
    """Use native include parsing; all standard headers are a single overapproximation."""
    root = Path(root)
    headers = {"ios", "new", "stdexcept", "typeinfo"}
    declarations = set()
    for directory in ("Includes", "Utility"):
        for path in sorted((root / "Cython" / directory).rglob("*")):
            if not path.is_file() or path.name == "ya.make" or "__pycache__" in path.parts:
                continue
            text = path.read_text(encoding="utf-8")
            headers.update(re.findall(r"cdef\s+extern\s+from\s+[\"']([^\"']+)[\"']", text))
            headers.update(re.findall(r'^\s*#\s*include\s*[<"]([^>"]+)[>"]', text, re.M))
            if directory == "Includes":
                name = path.relative_to(root / "Cython/Includes").as_posix()
                declarations.add(name)
                if name.endswith("/__init__.pxd"):
                    declarations.add(name.removesuffix("/__init__.pxd") + ".pxd")
    headers = {name.strip("<>") for name in headers if name != "*"}
    dynamic = sorted(name for name in headers if any(char in name for char in "%{}$"))
    if dynamic:
        raise ValueError("Non-literal standard headers require an explicit dependency: " + ", ".join(dynamic))
    (root / "induced_deps.h").write_text(
        "#pragma once\n\n// Dependency manifest, not a compilable header. Generated by yamaker.\n"
        + "".join("#include <{}>\n".format(name) for name in sorted(headers)),
        encoding="utf-8",
    )
    config = '- source_filter: "[.](pyx|pxd|pxi|py)$"\n  includes:\n'
    config += "".join("    - {}\n".format(name) for name in sorted(declarations))
    # Cython 3.2 contains a template for Python 3.14, which is not supplied in Arcadia yet.
    if "internal/pycore_template.h" in headers:
        config += '- source_filter: "^' + arcdir + '/induced_deps[.]h$"\n  includes:\n'
        config += "    - internal/pycore_template.h\n"
    (root / "sysincl.yml").write_text(config, encoding="utf-8")


def post_install(self):
    dist_files = python.extract_dist_info(self)

    re_sub_file(
        f"{self.dstdir}/cython.py",
        r"# Change content of this file to change uids for cython programs - cython.*",
        rf"# Change content of this file to change uids for cython programs - cython {self.version} r2",
    )

    for path, dirs, files in os.walk(self.dstdir):
        for file in files:
            if file.endswith(".c"):
                file = f"{path}/{file}"
                with open(file) as f:
                    first_line = f.readline()
                if first_line.startswith("/* Generated by Cython"):
                    os.remove(file)

    # Restore kept compiler files before collecting the runtime inputs.
    for name in ("Cython/_ResourceFiles.py", "Cython/Utility/CommonTypes.c"):
        preserved = Path(self.finaldir) / name
        if preserved.is_file():
            destination = Path(self.dstdir) / name
            destination.unlink(missing_ok=True)
            shutil.copyfile(preserved, destination)

    write_dependencies(self.dstdir, self.arcdir)
    sources, data = runtime_files(self.dstdir)
    self.yamakes.clear()
    self.yamakes["."] = self.module(
        module="PY3_LIBRARY",
        NO_LINT=True,
        ENABLE=["NO_PYTHON_INCLS"],
        # The resource wrapper imports six during coverage extraction.
        # Keep it with vendor sources to avoid lint and Python header dependencies.
        PY_SRCS=["TOP_LEVEL", "${ARCADIA_ROOT}/contrib/python/six/py3/six.py=six"] + sources,
        RECURSE=["bin", "deps"],
        RESOURCE_FILES=[Words("PREFIX", "cython/")] + data,
    )
    self.yamakes["deps"] = self.module(
        module="LIBRARY",
        LICENSE=["Apache-2.0"],
        ADDINCL=[
            Words("GLOBAL", path)
            for path in (
                "contrib/python/numpy/include/numpy/core/include",
                "contrib/python/numpy/include/numpy/core/include/numpy",
                "contrib/python/numpy/include/numpy/core/src/common",
                "contrib/python/numpy/include/numpy/core/src/npymath",
                "contrib/python/numpy/include/numpy/distutils/include",
            )
        ],
    )
    # License analysis normalizes PREFIX within each macro, so keep the groups separate.
    self.yamakes["."].before(
        "RESOURCE_FILES", Linkable(RESOURCE_FILES=python.prepare_resource_files(self, *dist_files))
    )


cython = NixProject(
    owners=["g:python-contrib"],
    arcdir="contrib/tools/cython_py2",
    nixattr=python.make_nixattr("cython"),
    copy_sources=["Cython/", "cygdb.py", "cython.py"],
    copy_sources_except=[".gitignore", ".gitlab*", "CMakeLists.txt", "__pycache__", "*.pyc", "*.pyo"],
    keep_paths=[
        "bin",
        "generated_c_headers.h",
        "generated_cpp_headers.h",
        "Cython/_ResourceFiles.py",
        "Cython/Utility/CommonTypes.c",
        "Cython/ya.make",
        "a.yaml",
    ],
    post_install=post_install,
)
